local function readFile(path)
    local f = io.open(path, "r") or io.open("src/" .. path, "r")
    if not f then return nil end
    local s = f:read("*a"); f:close()
    return s
end

local function single(mods)
    assert.are.equals(1, #mods)
    return mods[1]
end

describe("Lightning Blast Convergence flags parse (were ModCache NO-OPs)", function()
    it("' Lightning Blast Chains Only To First Target Hit' -> ChainsBackOnItself FLAG", function()
        local mods, extra = modLib.parseMod(" Lightning Blast Chains Only To First Target Hit")
        assert.is_truthy(extra == nil or extra == "")
        local m = single(mods)
        assert.are.equals("LightningBlastChainsBackOnItself", m.name)
        assert.are.equals("FLAG", m.type)
        assert.is_true(m.value)
    end)
    it("' Half Maximum Chains' -> HalfChains FLAG", function()
        local mods, extra = modLib.parseMod(" Half Maximum Chains")
        assert.is_truthy(extra == nil or extra == "")
        local m = single(mods)
        assert.are.equals("LightningBlastHalfChains", m.name)
        assert.are.equals("FLAG", m.type)
        assert.is_true(m.value)
    end)
end)

describe("Lightning Blast chain-count parsing (per-point + point-scaled)", function()
    -- Arcing Power (no '+'): 1-point cache row + >1-point scaled live-parse.
    it("'1 Maximum Additional Chains' -> MaxAdditionalChains BASE 1", function()
        local mods, extra = modLib.parseMod("1 Maximum Additional Chains")
        assert.is_truthy(extra == nil or extra == "",
            "was dropped with ' Maximum Additional Chains ' residue")
        local m = single(mods)
        assert.are.equals("MaxAdditionalChains", m.name)
        assert.are.equals("BASE", m.type)
        assert.are.equals(1, m.value)
    end)
    it("point-scaled '3 Maximum Additional Chains' (Arcing 3pt) -> BASE 3", function()
        local m = single(modLib.parseMod("3 Maximum Additional Chains"))
        assert.are.equals("MaxAdditionalChains", m.name)
        assert.are.equals(3, m.value)
    end)
    -- Chain Lightning ('+'): the same accumulator (sums with Arcing).
    it("'+1 Maximum Additional Chains' -> MaxAdditionalChains BASE 1", function()
        local m = single(modLib.parseMod("+1 Maximum Additional Chains"))
        assert.are.equals("MaxAdditionalChains", m.name)
        assert.are.equals(1, m.value)
    end)
    it("point-scaled '+2 Maximum Additional Chains' (Chain Lightning 2pt) -> BASE 2", function()
        local m = single(modLib.parseMod("+2 Maximum Additional Chains"))
        assert.are.equals("MaxAdditionalChains", m.name)
        assert.are.equals(2, m.value)
    end)
end)

