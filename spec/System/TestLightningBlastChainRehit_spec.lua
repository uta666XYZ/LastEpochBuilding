describe("Lightning Blast chain ModCache rows are no longer silent-failure NO-OPs", function()
    it("the six chain/cast rows carry mods, not empty residue stubs", function()
        local body = assert(readFile("Data/ModCache.lua"))
        assert.is_nil(body:find('c[" Half Maximum Chains"]={{},""}', 1, true))
        assert.is_nil(body:find('c[" Lightning Blast Chains Only To First Target Hit"]={{},""}', 1, true))
        assert.is_nil(body:find('c["1 Maximum Additional Chains"]={{}," Maximum Additional Chains "}', 1, true))
        assert.is_nil(body:find('c["8% Doublecast Chance"]={{}," Doublecast Chance "}', 1, true))
        assert.is_nil(body:find('c["30% Quadruple Cast Chance"]={{}," Quadruple Cast Chance "}', 1, true))
        -- and the parsed names are present
        assert.is_truthy(body:find("LightningBlastChainsBackOnItself", 1, true))
        assert.is_truthy(body:find("MaxAdditionalChains", 1, true))
    end)
    it("CalcOffence consumes the flag on the HitSpeed lever (node-gated)", function()
        local text = assert(readFile("Modules/CalcOffence.lua"))
        assert.is_truthy(text:find("LightningBlastChainsBackOnItself", 1, true),
            "the Convergence-gated hit multiplier must stay wired")
        assert.is_truthy(text:find("LightningBlastHitMult", 1, true))
    end)
end)
