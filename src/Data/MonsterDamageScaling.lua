local function clampLevel(l)
	l = l or 1
	if l < 0 then return 0 end
	if l > 100 then return 100 end
	return l
end

-- MORE damage percent a monster-actor minion authored at fromLevel receives when
-- scaled to toLevel (= (scale[toLevel]/scale[fromLevel] - 1) * 100, the value LEB's
-- modDB MORE expects in percent). Returns 0 if the basis is degenerate.
local function getMonsterDamageMorePercent(fromLevel, toLevel)
	local f = scale[clampLevel(fromLevel)]
	local t = scale[clampLevel(toLevel)]
	if not f or f == 0 or not t then return 0 end
	return (t / f - 1) * 100
end

return {
	scale = scale,
	getMonsterDamageMorePercent = getMonsterDamageMorePercent,
}
